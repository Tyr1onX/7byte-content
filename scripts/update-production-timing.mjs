import fs from 'node:fs/promises';
import path from 'node:path';

const episodeDir = process.argv[2];
const vttPath = process.argv[3];
if (!episodeDir || !vttPath) {
  throw new Error('usage: node scripts/update-production-timing.mjs <episode-dir> <vtt>');
}

const config = JSON.parse(await fs.readFile(path.join(episodeDir, 'production.json'), 'utf8'));
const vtt = await fs.readFile(vttPath, 'utf8');

const timeToSeconds = value => {
  const parts = value.trim().split(':').map(Number);
  if (parts.length === 3) return parts[0] * 3600 + parts[1] * 60 + parts[2];
  if (parts.length === 2) return parts[0] * 60 + parts[1];
  throw new Error(`Invalid VTT timestamp: ${value}`);
};

const cues = [];
const lines = vtt.replace(/\r/g, '').split('\n');
for (let i = 0; i < lines.length; i += 1) {
  if (!lines[i].includes('-->')) continue;
  const [rawStart, rawEnd] = lines[i].split('-->').map(part => part.trim().split(/\s+/)[0]);
  const text = [];
  i += 1;
  while (i < lines.length && lines[i].trim() !== '') {
    text.push(lines[i].replace(/<[^>]+>/g, ''));
    i += 1;
  }
  cues.push({
    start: timeToSeconds(rawStart),
    end: timeToSeconds(rawEnd),
    text: text.join(''),
  });
}

if (!cues.length) throw new Error('No subtitle cues found in final TTS VTT.');

const normalize = value => value
  .replace(/\s+/g, '')
  .replace(/[，。！？、；：“”‘’：,.!?;:'"()（）\-—]/g, '')
  .toLowerCase();

const markerStarts = [];
for (const marker of config.phaseMarkers ?? []) {
  const wanted = normalize(marker);
  let matched = null;
  for (let i = 0; i < cues.length; i += 1) {
    let joined = '';
    for (let j = i; j < Math.min(cues.length, i + 4); j += 1) {
      joined += normalize(cues[j].text);
      if (joined.includes(wanted)) {
        matched = cues[i].start;
        break;
      }
    }
    if (matched !== null) break;
  }
  if (matched === null) {
    throw new Error(`Phase marker not found in TTS subtitles: ${marker}`);
  }
  markerStarts.push(matched);
}

const T = [0, ...markerStarts];
for (let i = 1; i < T.length; i += 1) {
  if (!(T[i] > T[i - 1])) {
    throw new Error(`Production timing must be strictly increasing: ${JSON.stringify(T)}`);
  }
}

const timingModule = path.resolve(config.timingModule);
const moduleText = `// AUTO-GENERATED by scripts/update-production-timing.mjs from the final TTS.\n// Do not hand-edit timing values; regenerate the production build instead.\nexport const T = ${JSON.stringify(T)} as const;\nexport const BODY_END = T[T.length - 1];\nexport const SHOT_BOUNDARIES = T.slice(1, -1);\n`;
await fs.writeFile(timingModule, moduleText, 'utf8');

const result = {
  T,
  bodyEnd: T[T.length - 1],
  shotBoundaries: T.slice(1, -1),
  audioDuration: cues[cues.length - 1].end,
  cueCount: cues.length,
};
await fs.mkdir('output', {recursive: true});
await fs.writeFile('output/timing.json', JSON.stringify(result, null, 2) + '\n', 'utf8');
console.log(JSON.stringify(result));
