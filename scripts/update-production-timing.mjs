import fs from 'node:fs/promises';
import path from 'node:path';

const episodeDir = process.argv[2];
const wordTimingPath = process.argv[3];
if (!episodeDir || !wordTimingPath) {
  throw new Error('usage: node scripts/update-production-timing.mjs <episode-dir> <word-timing-json>');
}

const config = JSON.parse(await fs.readFile(path.join(episodeDir, 'production.json'), 'utf8'));
const wordTiming = JSON.parse(await fs.readFile(wordTimingPath, 'utf8'));
const words = wordTiming.words ?? [];
if (!words.length) throw new Error('No WordBoundary timing entries found.');

const normalize = value => value
  .replace(/\s+/g, '')
  .replace(/[，。！？、；：“”‘’：,.!?;:'"()（）\-—…]/g, '')
  .toLowerCase();

const markerStarts = [];
for (const marker of config.phaseMarkers ?? []) {
  const wanted = normalize(marker);
  let matched = null;

  for (let i = 0; i < words.length; i += 1) {
    let joined = '';
    for (let j = i; j < words.length && joined.length <= wanted.length + 24; j += 1) {
      joined += normalize(words[j].text ?? '');
      if (joined.includes(wanted)) {
        matched = Number(words[i].start);
        break;
      }
      if (joined.length > wanted.length + 24) break;
    }
    if (matched !== null) break;
  }

  if (matched === null || !Number.isFinite(matched)) {
    throw new Error(`Phase marker not found in WordBoundary timing: ${marker}`);
  }
  markerStarts.push(matched);
}

const T = [0, ...markerStarts];
for (let i = 1; i < T.length; i += 1) {
  if (!Number.isFinite(T[i]) || !(T[i] > T[i - 1])) {
    throw new Error(`Production timing must be finite and strictly increasing: ${JSON.stringify(T)}`);
  }
}

const timingModule = path.resolve(config.timingModule);
const moduleText = `// AUTO-GENERATED by scripts/update-production-timing.mjs from final TTS WordBoundary data.\n// Do not hand-edit timing values; regenerate the production build instead.\nexport const T = ${JSON.stringify(T)} as const;\nexport const BODY_END = T[T.length - 1];\nexport const SHOT_BOUNDARIES = T.slice(1, -1);\n`;
await fs.writeFile(timingModule, moduleText, 'utf8');

const lastWord = words[words.length - 1];
const audioDuration = Number(lastWord.end);
const result = {
  T,
  bodyEnd: T[T.length - 1],
  shotBoundaries: T.slice(1, -1),
  audioDuration,
  wordCount: words.length,
};
await fs.mkdir('output', {recursive: true});
await fs.writeFile('output/timing.json', JSON.stringify(result, null, 2) + '\n', 'utf8');
console.log(JSON.stringify(result));
